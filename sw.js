/*
 * Number Meadow worker (offline install). Classic worker script, no module syntax.
 *
 * What it does: keeps one cache per app version (nba-<version>-<hash>) and serves the page from the PINNED cache, cache first.
 * A new sw.js fills its own cache and then WAITS. It is used only after an adult approves it on the Grown-ups page and the app
 * is closed completely and opened again. The decisions (pin, approve, switch, fall back, clean up) are in
 * app/services/offline-model.js, loaded below, and are unit tested there.
 *
 * Rules this file keeps (static_checks.py, checks 16 and 19; tested again in sw_checks.py):
 *   - ASCII only, no web address in it.
 *   - It never takes over a window that is open (no early takeover, no claiming of windows): a version never changes in a session.
 *   - Its only network use is ONE call, in getFile(): a plain GET of a file named in PRECACHE, from its own host, with no
 *     query string and no body. The browser itself also re-reads this file now and then to look for a new version.
 *   - It reads and writes only Cache Storage (the caches and the small marker). It never touches the database or settings.
 *   - A page never waits on a stuck worker: if the cache has not answered in ANSWER_MAX_MS (2.5 s), the listed file is read from this
 *     copy's own host (backupFile); with the network off the page keeps waiting for the cache.
 *   - A message to the page holds only names, numbers and yes or no (safeAnswer in the model), never anything a child typed.
 */
