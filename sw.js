const M = self.NbaOfflineModel;
const SCOPE = self.registration.scope;
const SCOPE_URL = new URL(SCOPE);
const MARKER_KEY = 'nba-marker';  // the marker's key inside the cache nba-meta (a name, never fetched)
const FILES_KEY = 'nba-files';    // inside each version cache: the list of files that version holds (a name, never fetched)
const BATCH = 12;

const toUrl = (path) => new URL(path, SCOPE).href;
const toPath = (url) => {
  const u = new URL(url);
  return u.origin === SCOPE_URL.origin && u.pathname.indexOf(SCOPE_URL.pathname) === 0 ? u.pathname.slice(SCOPE_URL.pathname.length) : null;
};

/** The one network call: a GET of a listed file from this host. Anything else is refused before a request exists. */
function getFile(path) {
  if (PRECACHE.indexOf(path) < 0) throw new Error('not a listed path: ' + path);
  const u = new URL(path, SCOPE);
  if (u.origin !== SCOPE_URL.origin || u.search || u.hash) throw new Error('not a plain same-host address: ' + path);
  return fetch(new Request(u.href, { method: 'GET', cache: 'reload', credentials: 'same-origin' }));
}

const LAUNCH_WAIT_MS = 3000; // a page never waits longer than this for the launch decision
const JOB_MAX_MS = 15000;     // a job that has not finished by then no longer holds up the next one
const within = (promise, ms) => Promise.race([promise, new Promise((resolve) => setTimeout(resolve, ms))]);

let queue = Promise.resolve();
/** One job at a time in this worker (the marker is read, changed and written back). */
function serial(job) {
  const run = queue.then(job, job);
  queue = within(run.catch(() => undefined), JOB_MAX_MS);
  return run;
}

async function readMarker() {
  const meta = await caches.open(M.META_CACHE);
  const hit = await meta.match(toUrl(MARKER_KEY));
  return hit ? M.parseMarker(await hit.text()) : M.emptyMarker();
}
async function writeMarker(marker) {
  const meta = await caches.open(M.META_CACHE);
  await meta.put(toUrl(MARKER_KEY), new Response(M.writeMarker(marker), { headers: { 'Content-Type': 'application/json' } }));
}
async function allMarkers() {
  const meta = await caches.open(M.META_CACHE);
  const out = [];
  for (const key of await meta.keys()) {
    const hit = await meta.match(key);
    if (hit) out.push(M.parseMarker(await hit.text()));
  }
  return out;
}

/** Self-check of one cache: is every file that cache's own list names inside it? ({ ready, missing, total }) */
async function check(cacheName) {
  const none = { ready: false, missing: 0, total: 0 };
  if (!cacheName || !(await caches.has(cacheName))) return none;
  const cache = await caches.open(cacheName);
  const listFile = await cache.match(toUrl(FILES_KEY));
  if (!listFile) return none;
  let listed = [];
  try { listed = await listFile.json(); } catch (e) { return none; }
  const have = (await cache.keys()).map((k) => toPath(k.url));
  return M.readiness(listed, have);
}

async function cleanUp(abandon) {
  const gone = M.deletions(await caches.keys(), await allMarkers(), CACHE_NAME, abandon);
  await Promise.all(gone.map((n) => caches.delete(n)));
}

let pinnedNow = null;
async function pinnedName() {
  if (!pinnedNow) pinnedNow = (await readMarker()).pinned;
  return pinnedNow;
}

/** The decision at a launch (this worker just activated, or a page is being opened). Never switches while another window is open. */
async function launch(source) {
  const marker = await readMarker();
  const existing = await caches.keys();
  const windows = await self.clients.matchAll({ type: 'window', includeUncontrolled: true });
  const verdict = M.settle({ marker: marker, mine: CACHE_NAME, source: source, others: windows.length, existing: existing,
    mineReady: (await check(CACHE_NAME)).ready, pinnedReady: (await check(marker.pinned)).ready, previousReady: (await check(marker.previous)).ready });
  if (M.writeMarker(verdict.marker) !== M.writeMarker(marker)) await writeMarker(verdict.marker);
  pinnedNow = verdict.marker.pinned;
  if (verdict.action !== 'none' && verdict.action !== 'ack') await cleanUp(verdict.abandon);
  return verdict;
}

self.addEventListener('install', (event) => {
  event.waitUntil(serial(async () => {
    await writeMarker(M.noteInstalling(await readMarker(), CACHE_NAME));
    try {
      const cache = await caches.open(CACHE_NAME);
      for (let i = 0; i < PRECACHE.length; i += BATCH) {
        await Promise.all(PRECACHE.slice(i, i + BATCH).map(async (path) => {
          const res = await getFile(path);
          if (!res.ok) throw new Error('could not get ' + path + ': ' + res.status);
          await cache.put(toUrl(path), res);
        }));
      }
      await cache.put(toUrl(FILES_KEY), new Response(JSON.stringify(PRECACHE), { headers: { 'Content-Type': 'application/json' } }));
    } catch (e) {
      if (CACHE_NAME !== (await readMarker()).pinned) await caches.delete(CACHE_NAME); // a failed download leaves no half copy behind
      throw e;
    }
    await writeMarker(M.afterInstall(await readMarker(), CACHE_NAME, await caches.keys()));
  }));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(within(serial(() => launch('activate')).catch(() => undefined), LAUNCH_WAIT_MS));
});

async function answer(request) {
  const isPage = request.mode === 'navigate';
  if (isPage) await within(serial(() => launch('navigate')).catch(() => undefined), LAUNCH_WAIT_MS);
  const pinned = await pinnedName();
  let path = toPath(request.url);
  if (path === '' && isPage) path = 'index.html';
  if (pinned && path !== null) {
    const cache = await caches.open(pinned);
    const hit = await cache.match(toUrl(path));
    if (hit) return hit;
    if (pinned === CACHE_NAME && PRECACHE.indexOf(path) >= 0) { // this copy's own file is missing: fetch it again and keep it
      const again = await getFile(path);
      if (again.ok) await cache.put(toUrl(path), again.clone());
      return again;
    }
  }
  return new Response('Not in the offline copy.', { status: 404, statusText: 'Not Found', headers: { 'Content-Type': 'text/plain' } });
}

const ANSWER_MAX_MS = 2500; // a page never waits longer than this on the worker's own queue or cache before the host may answer
const STUCK_MEMORY_MS = 60000; // after the host had to answer once, the next files are asked for at once for this long (not 3 s each)
let stuckAt = 0;

/** The backup after ANSWER_MAX_MS: the same listed file from this copy's own host. Not used when another version is pinned (it could be a
 *  different version of the file), nor for a file that is not listed. null means "keep waiting for the cache". */
async function backupFile(request) {
  let path = toPath(request.url);
  if (path === '' && request.mode === 'navigate') path = 'index.html';
  if (path === null || PRECACHE.indexOf(path) < 0) return null;
  if (pinnedNow && pinnedNow !== CACHE_NAME) return null;
  const res = await getFile(path);
  if (res.ok) stuckAt = Date.now();
  return res.ok ? res : null;
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || toPath(request.url) === null) return; // not ours: the browser handles it as usual
  event.respondWith(M.answerOrBackup(answer(request), () => backupFile(request), Date.now() - stuckAt < STUCK_MEMORY_MS ? 0 : ANSWER_MAX_MS));
});

/** The page asks (status) or approves (approve). The answer travels on the page's own message port. */
self.addEventListener('message', (event) => {
  const port = event.ports && event.ports[0];
  const type = event.data && event.data.type;
  if (!port || (type !== 'status' && type !== 'approve')) return;
  event.waitUntil(serial(async () => {
    let marker = await readMarker();
    const mine = await check(CACHE_NAME);
    let ok = true, reason = 'status';
    if (type === 'approve') {
      const r = M.afterApprove(marker, CACHE_NAME, mine.ready);
      ok = r.ok; reason = r.reason; marker = r.marker;
      if (ok) await writeMarker(marker);
    }
    const pinned = await check(marker.pinned);
    port.postMessage(M.safeAnswer({ type: type, ok: ok, reason: reason, mine: CACHE_NAME, pinned: marker.pinned, approved: marker.approved,
      previous: marker.previous, ready: pinned.ready, mineReady: mine.ready, missing: pinned.missing, total: pinned.total,
      update: !!marker.pinned && marker.pinned !== CACHE_NAME && mine.ready, isApproved: marker.approved === CACHE_NAME }));
  }).catch(() => undefined));
});
